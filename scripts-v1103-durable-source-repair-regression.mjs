assert.match(src,/async function repairSceneCloudMedia\(/,'cloud self-repair helper required');
assert.match(src,/async function ensureSceneSourceForServer\(/,'server source gate required');
assert.match(src,/const videoUrl=await ensureSceneSourceForServer\(projectId,episodeId,index\)/,'Finish clip must use verified/repaired source');
assert.match(src,/upsert:true/,'repair must be able to restore a missing cloud object');
