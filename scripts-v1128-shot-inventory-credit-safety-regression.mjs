import fs from 'node:fs';
import assert from 'node:assert/strict';
const app=fs.readFileSync(new URL('./app.js',import.meta.url),'utf8');
const css=fs.readFileSync(new URL('./styles.css',import.meta.url),'utf8');
const pkg=JSON.parse(fs.readFileSync(new URL('./package.json',import.meta.url),'utf8'));
const html=fs.readFileSync(new URL('./index.html',import.meta.url),'utf8');
assert.equal(pkg.version,'1.12.4');
assert.ok(app.includes("const APP_VERSION = '1.12.4'"));
assert.ok(html.includes('/app.js?v=1.12.4')&&html.includes('/styles.css?v=1.12.4'));
assert.ok(app.includes('function sceneShotMediaInventory('),'missing explicit shot-media inventory');
assert.ok(app.includes("state='recreate'"),'expired/legacy shots must be distinct from ordinary planned shots');
assert.ok(app.includes("return {label:'RECREATE',kind:'attention'}"),'expired legacy media must be visible in the shot plan');
assert.ok(app.includes('need generation'),'shot-plan summary must expose missing generation work');
assert.ok(app.includes('need dialogue sync'),'shot-plan summary must expose dialogue-only work');
assert.ok(!app.includes('existing valid media is preserved'),'misleading blanket preservation copy must be removed');
assert.ok(app.includes('Completed durable media will be reused'),'one-click confirmation must promise missing-shot generation only');
assert.ok(app.includes('CURRENT PAID WORK'),'credit-use warning must be explicit');
assert.ok(app.includes('Saved shot ${shot.order} for scene ${scene?.number||sceneIndex+1} could not be restored. CineTale will not spend credits regenerating a durable shot automatically.'),'durable unhydrated shots must fail closed instead of being regenerated');
assert.ok(css.includes('.scene-shot-card.attention'),'expired legacy shots must have a distinct visual state');
console.log('v1.11.0 shot inventory + credit safety regression PASS');
