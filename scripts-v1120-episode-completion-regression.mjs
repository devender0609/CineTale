import fs from 'node:fs';
import assert from 'node:assert/strict';
const app=fs.readFileSync('app.js','utf8');
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
const html=fs.readFileSync('index.html','utf8');
assert.equal(pkg.version,'1.12.4');
assert.ok(app.includes("const APP_VERSION = '1.12.4'"));
assert.ok(html.includes('/app.js?v=1.12.4')&&html.includes('/styles.css?v=1.12.4'));

// Protect current synchronized scenes: current durable source is defined separately from final AV readiness.
assert.ok(app.includes('function sceneSourceMatchesCurrentProduction(project={},scene={})'));
assert.ok(app.includes('sceneVideoProductionProvenanceValid(project,scene)'));
assert.ok(app.includes('function sceneNeedsModernSource(project={},scene={})'));
assert.ok(app.includes("if(project&&sceneNeedsModernSource(project,scene))return 'modernize'"));
assert.ok(app.includes("if(action==='modernize')return 'Update clip'"));

// Legacy/mismatched source clips must be regenerated by automatic episode completion, not rescued as current.
assert.ok(app.includes('const missing=selected.filter(x=>!sceneSourceMatchesCurrentProduction(p,x.scene))'));
assert.ok(app.includes('const legacyNeedsRefresh=sceneNeedsModernSource(p,scene)'));
assert.ok(app.includes("scene.videoUrl&&!legacyNeedsRefresh"));
assert.ok(app.includes('!sceneSourceMatchesCurrentProduction(liveAfterSubmit,s)'));
assert.ok(app.includes('remaining=selectedNow.filter(x=>!sceneSourceMatchesCurrentProduction(live,x.scene))'));

// A replacement render must not relabel the old source with the new production contract while Veo is still running.
assert.ok(app.includes('target.videoPendingPrimaryMeta={...primaryMeta}'));
assert.ok(app.includes('target.videoPendingProductionContract=productionContract'));
assert.ok(app.includes('const pending=pendingPrimaryVideoPatch(target);resetSceneLipSyncForNewSource(target,providerUrl);Object.assign(target,pending,patch);clearPendingPrimaryVideoState(target)'));
const requestOperationBlock=app.slice(app.indexOf("if(d.operation){",app.indexOf('async function requestVideo')), app.indexOf("toast('Video rendering started",app.indexOf('async function requestVideo')));
assert.ok(!requestOperationBlock.includes('target.videoProductionContract=productionContract'),'old source must not receive the replacement contract before the new file commits');

// Resume/poll must wait for the replacement operation rather than returning the still-visible legacy source URL.
assert.ok(app.includes("if(!scene.videoOperation&&sceneSourceMatchesCurrentProduction(p,scene))return scene.videoUrl"));

// Workflow should advance toward one finished episode, preserving completed scenes.
assert.ok(app.includes("action:'finish-production'"));
assert.ok(app.includes("createFinalVideoAutomatically({resume:false})"));
assert.ok(app.includes('rebuild only legacy or missing clips'));

// Tiny behavioral model: two good scenes remain protected, three legacy scenes are the only rebuild targets.
const current=(s)=>s.owned&&(!s.speaking||s.provenance);
const scenes=[
  {owned:true,speaking:true,provenance:true,validated:true},
  {owned:true,speaking:true,provenance:true,validated:true},
  {owned:false,speaking:true,provenance:false,validated:false},
  {owned:false,speaking:true,provenance:false,validated:false},
  {owned:false,speaking:true,provenance:false,validated:false},
];
assert.deepEqual(scenes.map((s,i)=>current(s)?null:i).filter(i=>i!==null),[2,3,4]);
console.log('v1.10.20 episode completion / legacy modernization regression PASS');
