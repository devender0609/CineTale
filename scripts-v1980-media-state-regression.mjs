import fs from 'node:fs';
import assert from 'node:assert/strict';
const app=fs.readFileSync(new URL('./app.js',import.meta.url),'utf8');
const css=fs.readFileSync(new URL('./styles.css',import.meta.url),'utf8');
const html=fs.readFileSync(new URL('./index.html',import.meta.url),'utf8');
const pkg=JSON.parse(fs.readFileSync(new URL('./package.json',import.meta.url),'utf8'));
assert.equal(pkg.version,'1.12.4');
assert.ok(app.includes("const APP_VERSION = '1.12.4'"));
assert.ok(html.includes('/app.js?v=1.12.4')&&html.includes('/styles.css?v=1.12.4'));
assert.ok(app.includes('const studioVideoFallbacks=new Map()'),'studio fallback registry missing');
assert.ok(app.includes('function sceneStudioCandidateUrls'),'studio source fallback candidates missing');
assert.ok(app.includes("video.dataset.voiceSync='visual-only'"),'sync-gated preview must identify visual-only review mode');
assert.ok(!app.slice(app.indexOf("video.addEventListener('play'"),app.indexOf("video.addEventListener('pause'")).includes('startSceneVideoVoicePlayback'),'sync-gated previews must not layer detached audio over source video');
assert.ok(app.includes("video.addEventListener('volumechange',()=>{if(video.dataset.syncGated==='1'&&!video.muted)video.muted=true})"),'unsynchronized speaking source must remain muted even if native controls try to unmute it');
assert.ok(app.includes("videoMediaExpired=true"),'unavailable media state missing');
assert.ok(app.includes("studioVideoFallbacks.set(key"),'failed source must be able to fail over to another saved clip');
assert.ok(app.includes("if(scene?.videoUrl)return '';"),'technical preview labels must stay off playable video surfaces');
assert.ok(css.includes('video[data-sync-gated="1"]{pointer-events:auto'),'sync-gated media controls must stay interactive');
console.log('v1.12.4 media-state + approved-audio preview + source-fallback regression PASS');
