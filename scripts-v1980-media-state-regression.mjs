import fs from 'node:fs';
import assert from 'node:assert/strict';
const app=fs.readFileSync(new URL('./app.js',import.meta.url),'utf8');
const css=fs.readFileSync(new URL('./styles.css',import.meta.url),'utf8');
const html=fs.readFileSync(new URL('./index.html',import.meta.url),'utf8');
const pkg=JSON.parse(fs.readFileSync(new URL('./package.json',import.meta.url),'utf8'));
assert.equal(pkg.version,'1.9.80');
assert.ok(app.includes("const APP_VERSION = '1.9.80'"));
assert.ok(html.includes('/app.js?v=1.9.80')&&html.includes('/styles.css?v=1.9.80'));
assert.ok(app.includes('const studioVideoFallbacks=new Map()'),'studio fallback registry missing');
assert.ok(app.includes('function sceneStudioCandidateUrls'),'studio source fallback candidates missing');
assert.ok(app.includes("video.dataset.voiceSync='approved-preview'"),'sync-gated preview must identify approved-audio review mode');
assert.ok(!app.includes("video.dataset.voiceSync='waiting-for-render';\n      video.addEventListener('volumechange',()=>{if(!video.muted)video.muted=true});\n      return;"),'sync-gated previews must not return before approved audio handlers are bound');
assert.ok(app.includes("provider/source speech remains suppressed"),'audio failure must not restore provider speech');
assert.ok(app.includes("video.dataset.voiceSync='media-unavailable'"),'unavailable media state missing');
assert.ok(app.includes("studioVideoFallbacks.set(key"),'failed source must be able to fail over to another saved clip');
assert.ok(app.includes("'Source preview + approved voice'"),'creator-facing preview state missing');
assert.ok(css.includes('video[data-sync-gated="1"]{pointer-events:auto'),'sync-gated media controls must stay interactive');
console.log('v1.9.80 media-state + approved-audio preview + source-fallback regression PASS');
